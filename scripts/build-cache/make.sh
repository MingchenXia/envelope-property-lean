#!/bin/bash
# Pack the compiled Lake artifacts of this repository (<package>/.lake/build/{lib,ir}) into
# xz-compressed tar chunks of 45 MB plus a MANIFEST with their sha256 (see ../../BUILD-CACHE.md).
#
#   scripts/build-cache/make.sh OUTDIR                    # write OUTDIR/{MANIFEST,README.md,chunk.NNNN}
#   scripts/build-cache/make.sh --push-branch OUTDIR      # ... and commit them to the orphan branch
#                                                         #     `build-cache` of origin and push
#   scripts/build-cache/make.sh --release TAG OUTDIR      # ... and upload them as assets of the GitHub
#                                                         #     release TAG (gh CLI)
#
# REUSE=1 publishes the chunks already in OUTDIR (from an earlier run, possibly packed in an
# untracked copy of the same tree) without packing again; MANIFEST's release-commit is then set to
# the HEAD of this checkout.
# Run it only after `cd EnvelopeProperty && lake build --no-build` succeeds, i.e. when every module
# of the release is up to date. *.setup.json (regenerated by Lake) and *.nobuild markers are not
# packed. GitHub limits: 100 MB per file (chunks are 45 MB), 2 GB per push (the branch is pushed in
# batches of at most 20 chunks).
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
MODE=dir TAG=""
case "${1:-}" in
  --push-branch) MODE=branch; shift ;;
  --release) MODE=release; TAG=${2:?release tag}; shift 2 ;;
esac
OUT=${1:?usage: make.sh [--push-branch | --release TAG] OUTDIR}
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
cd "$ROOT"
if [ "${REUSE:-0}" = 1 ] && [ -f "$OUT/MANIFEST" ]; then
  # publish chunks packed earlier (by this script) without packing again
  chunks=$(cd "$OUT" && ls chunk.* | sort); n=$(echo "$chunks" | wc -l)
  # chunks packed in an untracked copy of the same tree: record the commit being published
  if head_commit=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null); then
    sed -i "s/^release-commit: .*/release-commit: $head_commit/" "$OUT/MANIFEST"
  fi
  release_commit=$(sed -n 's/^release-commit: //p' "$OUT/MANIFEST")
  [ -f "$OUT/README.md" ] || cp BUILD-CACHE.md "$OUT/README.md"
  echo "reusing $n chunks in $OUT (release-commit $release_commit)" >&2
else
rm -f "$OUT"/chunk.* "$OUT"/MANIFEST
dirs=$(for d in EnvelopeProperty EnvelopeProperty/deps/* TranscendentalNakamaye DeJongAlterations \
                SGPTFormalization BingWangEntropy; do
         if [ -d "$d/.lake/build" ]; then echo "$d/.lake/build"; fi; done)
[ -n "$dirs" ] || { echo "no .lake/build directories under $ROOT" >&2; exit 1; }
release_commit=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo "none (not a git checkout)")
workspace_rev=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["source_workspace_revision"])' \
                  RELEASE-MANIFEST.json 2>/dev/null || echo unknown)
mathlib=$(python3 -c 'import json,sys; m=json.load(open(sys.argv[1])); print([p["rev"] for p in m["packages"] if p["name"]=="mathlib"][0])' \
            EnvelopeProperty/lake-manifest.json)
nolean=$(find $dirs -name '*.olean' | wc -l)
echo "packing $nolean modules from: $(echo $dirs)" >&2
tar -cf - --exclude='*.setup.json' --exclude='*.nobuild' --sort=name --owner=0 --group=0 --numeric-owner $dirs \
  | nice -n 15 xz -T"${XZ_THREADS:-2}" -6 | split -b 45M -d -a 4 - "$OUT/chunk."
chunks=$(cd "$OUT" && ls chunk.* | sort)
n=$(echo "$chunks" | wc -l)
{
  echo "release-commit: $release_commit"
  echo "workspace-revision: $workspace_rev"
  echo "created: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "lean: $(cat EnvelopeProperty/lean-toolchain)"
  echo "mathlib: $mathlib (fetch its oleans with: cd EnvelopeProperty && lake exe cache get)"
  echo "modules: $nolean"
  echo "format: tar | xz, split into 45 MB chunks; extract at the repository root"
  echo "directories:"; for d in $dirs; do echo "  - $d"; done
  echo "chunks: $n"
  (cd "$OUT" && sha256sum $chunks)
} > "$OUT/MANIFEST"
cp BUILD-CACHE.md "$OUT/README.md"
echo "wrote $n chunks ($(du -sh "$OUT" | cut -f1)) to $OUT" >&2
fi

case $MODE in
  branch)
    TMPI=$(mktemp -d "${TMPDIR:-/tmp}/build-cache-index.XXXXXX"); trap 'rm -rf "$TMPI"' EXIT
    export GIT_INDEX_FILE="$TMPI/index"
    parent=""; i=0; last=""
    for c in $chunks; do
      git update-index --add --cacheinfo 100644 "$(git hash-object -w "$OUT/$c")" "chunks/$c"
      i=$((i+1))
      if [ $((i % 20)) -eq 0 ] || [ $i -eq $n ]; then
        for f in MANIFEST README.md; do
          git update-index --add --cacheinfo 100644 "$(git hash-object -w "$OUT/$f")" "$f"
        done
        t=$(git write-tree)
        msg="build cache of $release_commit ($i/$n chunks)"
        if [ -z "$parent" ]; then last=$(git commit-tree "$t" -m "$msg")
        else last=$(git commit-tree "$t" -p "$parent" -m "$msg"); fi
        for try in 1 2 3 4; do git push -f origin "$last:refs/heads/build-cache" && break; sleep $((2**try)); done
        parent=$last
      fi
    done
    echo "pushed build-cache $last ($n chunks)" >&2 ;;
  release)
    (cd "$OUT" && gh release upload "$TAG" MANIFEST $chunks --clobber)
    echo "uploaded $n chunks + MANIFEST to release $TAG" >&2 ;;
esac
